import type { Metadata } from "next";
import { Inter } from "next/font/google";
import "./globals.css";
import { Toaster } from "@/components/ui/toaster";
import { UserProvider } from '@/lib/context/UserContext'
import { getCurrentUser, getUserPermissions } from '@/actions/user.actions'
import { AuthProviderClient } from '@/components/auth-provider-client';

const inter = Inter({ subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // Get user data from server action (serializable)
  const { user } = await getCurrentUser()
  
  // Get user permissions from server action (serializable)
  const { groupPermissions } = user ? await getUserPermissions(user.id) : { groupPermissions: {} }

  return (
    <html lang="en">
      <body className={inter.className}>
        <UserProvider 
          initialUser={user}
          initialGroupPermissions={groupPermissions}
        >
          <AuthProviderClient>
            {children}
          </AuthProviderClient>
          <Toaster />
        </UserProvider>
      </body>
    </html>
  );
}
